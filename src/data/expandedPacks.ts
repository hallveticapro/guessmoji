export const expandedPuzzles = expandedPackSeeds.flatMap((pack) =>
  pack.cards.map(
    ([answer, emojis, hint, details, funFact, difficulty = "easy", explanation]) => ({
      id: `${pack.id}-${slugify(answer)}`,
      answer,
      emojis,
      categoryId: pack.id,
      difficulty,
      hint,
      details,
      explanation,
      funFact,
      tags: [...new Set([...pack.tags, pack.id])],
    }),
  ),
) satisfies Puzzle[];

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
